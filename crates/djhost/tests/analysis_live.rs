//! The analysis against a live engine, offline (docs/BEAT-DETECTION.md): the history head
//! snapped to a bar line, a bar-exact loop cut from a scrubbed position, a freeze timed to a bar
//! line, and a latency estimate of a source that arrives late on the master clock.
//!
//! The input is a click on every beat (an impulse of 1.0, the bar's first beat twice as loud),
//! with the bar line placed where the test says, so where a click lands says where the head is.

use djengine::beatgrid::{Anchor, FrameGrid, Unit};
use djengine::history::Mode;
use djhost::analysis::live::{self, SnapWatch};
use djhost::deck::{engine, Engine, EngineConfig, Renderer};
use djrust::TrackSpec;

const SR: f64 = 48_000.0;
const BLOCK: usize = 256;
/// A beat at 120 BPM.
const BEAT: usize = 24_000;
const BAR: usize = 4 * BEAT;

struct Rig {
    e: Engine,
    r: Renderer,
    feed: rtrb::Producer<f32>,
    fed: usize,
    out: Vec<f32>,
    /// Where the clicks are: (frame, amplitude), generated by `click`.
    click: Box<dyn Fn(usize) -> f32>,
}

impl Rig {
    /// A click every beat, a loud one every bar, the bar's click at `phase` frames into it.
    fn new(phase: usize) -> Rig {
        let mut c = EngineConfig::new(SR);
        c.extended = false;
        c.inputs = vec!["TD-3".into()];
        let (mut e, r) = engine(c);
        let (feed, _) = e.take_input_feed(0).unwrap();
        e.set_input_trim(0, 0.0);
        e.set_input_volume(0, 1.0);
        e.set_crossfader(0.5);
        e.set_free_bpm(120.0);
        e.sync_history_tempo();
        Rig {
            e,
            r,
            feed,
            fed: 0,
            out: Vec::new(),
            click: Box::new(move |f| {
                if f % BEAT != phase % BEAT {
                    0.0
                } else if (f / BEAT) % 4 == phase / BEAT % 4 {
                    1.0
                } else {
                    0.5
                }
            }),
        }
    }

    fn run(&mut self, frames: usize) {
        let (mut l, mut rr) = (vec![0f32; BLOCK], vec![0f32; BLOCK]);
        for _ in 0..frames / BLOCK {
            for k in 0..BLOCK {
                let _ = self.feed.push((self.click)(self.fed + k));
            }
            self.fed += BLOCK;
            self.r.render_block(&mut l, &mut rr);
            self.e.sync_history_tempo();
            self.e.service_loops();
            self.out.extend_from_slice(&l);
        }
    }

    fn beats(&mut self, n: f64) {
        self.run((n * BEAT as f64) as usize);
    }
}

/// Frames holding a click (|x| over the threshold), one per click.
fn clicks(x: &[f32], from: usize, over: f32) -> Vec<usize> {
    let mut v = vec![];
    let mut k = from;
    while k < x.len() {
        if x[k].abs() > over {
            v.push(k);
            k += 2000;
        } else {
            k += 1;
        }
    }
    v
}

/// The grid of the click track: bar 1 at frame `origin` of the recording.
fn grid(origin: f64) -> FrameGrid {
    FrameGrid { origin, period: BEAT as f64, beats_per_bar: 4 }
}

#[test]
fn a_released_scrub_lands_on_the_bar_line() {
    // the loud click is 6000 frames after each bar line: the grid says where the bar starts,
    // the click says where the head went
    let mut g = Rig::new(7 + 6000);
    g.beats(14.0);
    let gr = grid(7.0);
    let mut watch = SnapWatch::new();
    let on_grid = |_: usize| Some(gr);
    // a hand touches the platter, scrubs back 5.3 beats, and lets go (scrub, then delay): the
    // watcher sees the touch, then the release
    assert!(g.e.input_touch(0));
    assert!(g.e.input_scrub_beats(0, -5.3));
    g.run(BLOCK * 8);
    assert!(watch.service(&mut g.e, Some(Unit::Bar), &on_grid).is_empty(), "nothing to snap while held");
    g.e.input_release(0);
    g.run(BLOCK * 4);
    assert_eq!(g.e.inputs[0].mirror.history_mode(), Mode::Play);
    let t0 = g.out.len();
    let mut moves = watch.service(&mut g.e, Some(Unit::Bar), &on_grid);
    assert_eq!(moves.len(), 1, "the release was snapped");
    let end = g.e.inputs[0].mirror.tap.get().unwrap().end() as f64;
    // a second pass right after leaves it alone (its own touch and release are not a hand's)
    g.run(BLOCK * 4);
    assert!(watch.service(&mut g.e, Some(Unit::Bar), &on_grid).is_empty());
    let mv = moves.remove(0).1.unwrap();
    assert_eq!(mv.unit, Unit::Bar);
    assert!(!mv.live);
    // the lag is a whole number of bars (+ the bit the recording is past a line)
    let line_of_lag = end - mv.lag_frames;
    assert!(((line_of_lag - 7.0) / BAR as f64 - ((line_of_lag - 7.0) / BAR as f64).round()).abs() < 1e-6, "{line_of_lag}");
    g.run(BLOCK * 40);
    // the head is on the line: the loud click comes 6000 frames later, then a beat click every beat
    let loud = clicks(&g.out, t0 + 1500, 0.75);
    let first = loud.first().copied().expect("a loud click");
    let dt = first as i64 - t0 as i64;
    eprintln!("MEASURE snap: the loud click came {dt} frames after the snap (6000 expected)");
    assert!((dt - 6000).abs() < 900, "the loud click came {dt} frames after the snap (6000 expected)");
}

#[test]
fn a_loop_is_cut_on_bar_lines_from_the_head_and_is_exact() {
    let mut g = Rig::new(7);
    g.beats(22.5);
    let gr = grid(7.0);
    // live: the last two whole bars
    let a = live::capture_bars(&mut g.e, 0, &gr, 2, Anchor::End).unwrap();
    assert_eq!((a.bars, a.beats), (2, 8));
    assert_eq!(a.end - a.start, 2 * BAR as i64);
    assert_eq!((a.start - 7) % BAR as i64, 0, "starts on a bar line");
    assert!((a.bpm - 120.0).abs() < 1e-9, "{}", a.bpm);
    let c = g.e.clip(&a.id).unwrap();
    assert_eq!(c.buffer.left.len(), 2 * BAR);
    // the loud click is the first sample of the loop (the strip's DC block leaves most of it)
    assert!(c.buffer.left[0] > 0.8, "{}", c.buffer.left[0]);
    assert!(c.buffer.left[BEAT] > 0.3 && c.buffer.left[BEAT] < 0.7);
    assert!(c.buffer.left[BAR] > 0.8, "the second bar starts on a loud click too");
    assert_eq!(c.beats, 8);

    // scrubbed back 9.4 beats: the head is nearest the bar line 2 bars back; start anchor takes
    // the bars from there
    g.e.input_touch(0);
    g.e.input_scrub_beats(0, -9.4);
    g.run(BLOCK * 6);
    let h = live::head(&g.e, 0).unwrap();
    assert!(matches!(h.mode, Mode::Touch | Mode::Play));
    let b = live::capture_bars(&mut g.e, 0, &gr, 1, Anchor::Start).unwrap();
    assert_eq!(b.end - b.start, BAR as i64);
    assert_eq!((b.start - 7) % BAR as i64, 0);
    // 9.4 beats back from ~22.5 is beat 13.1: nearest bar line is beat 12
    let line_beat = (b.start as f64 - 7.0) / BEAT as f64;
    assert!((line_beat - 12.0).abs() < 1e-9, "{line_beat}");
    let c = g.e.clip(&b.id).unwrap();
    assert!(c.buffer.left[0] > 0.8);
    // asking for more than is recorded is an error that says so
    let e = live::capture_bars(&mut g.e, 0, &gr, 8, Anchor::End).unwrap_err();
    assert!(e.contains("recording"), "{e}");
}

#[test]
fn a_freeze_waits_for_the_bar_line() {
    let mut g = Rig::new(7);
    g.beats(9.3);
    let gr = grid(7.0);
    let plan = live::plan_freeze(&g.e, 0, &gr, 1, BLOCK as f64).unwrap();
    assert_eq!(plan.beats, 4.0);
    assert_eq!((plan.line - 7.0) % BAR as f64, 0.0);
    let end0 = g.e.inputs[0].mirror.tap.get().unwrap().end() as f64;
    assert!(plan.line > end0);
    let mut fired = None;
    for _ in 0..(BEAT * 4 / BLOCK) {
        g.run(BLOCK);
        if let Some(r) = live::service_freeze(&mut g.e, &plan) {
            fired = Some(r.unwrap());
            break;
        }
    }
    let f = fired.expect("the freeze fired");
    // it fired within a block of the line
    eprintln!("MEASURE freeze: fired {:.0} frames from the line", f.end_error_frames);
    assert!(f.end_error_frames.abs() <= BLOCK as f64, "{f:?}");
    g.run(BLOCK * 4);
    assert_eq!(g.e.inputs[0].mirror.freeze_state(), 2, "frozen");
    assert!((g.e.inputs[0].mirror.freeze_beats() - 4.0).abs() < 0.01);
    // too long a freeze says what fits
    let e = live::plan_freeze(&g.e, 0, &gr, 8, BLOCK as f64).unwrap_err();
    assert!(e.contains("at most"), "{e}");
}

#[test]
fn a_source_late_on_the_clock_is_measured() {
    // a deck plays, so there is a master clock; the source plays on that clock, 35 ms late
    let mut g = Rig::new(7);
    g.e.set_volume("A", 1.0);
    assert!(g.e.generate("A", &TrackSpec::new("techno", 42.0, None)));
    g.e.play("A");
    g.run(BLOCK * 16);
    let (beat0, fpb) = g.e.clock_beat_now().expect("a master clock");
    let end0 = g.e.inputs[0].mirror.tap.get().unwrap().end() as f64;
    // recording frame of clock beat b, as the capture path has it
    let f_clock = |b: f64| end0 - (beat0 - b) * fpb;
    let late = (0.035 * SR).round();
    let first = (beat0.ceil() + 1.0) as i64;
    let click_frames: std::collections::BTreeSet<usize> =
        (first..first + 80).map(|b| (f_clock(b as f64) + late).round() as usize).collect();
    g.click = Box::new(move |f| if click_frames.contains(&f) { 1.0 } else { 0.0 });
    // 16 beats of it, then ask
    g.run((fpb * 20.0) as usize);
    let lr = live::latency_ref(&g.e, 0, 12.0).unwrap();
    assert!((lr.clock_bpm - 60.0 * SR / fpb).abs() < 1e-6);
    // detect the clicks as onsets and fold on the clock's beat
    let on = djhost::analysis::dsp_onsets(&lr.window.audio, SR);
    let times: Vec<f64> = on.iter().map(|o| o.0).collect();
    let w: Vec<f64> = on.iter().map(|o| o.1).collect();
    let est = djengine::beatgrid::estimate_latency(&times, &w, lr.period, lr.origin).unwrap();
    eprintln!("MEASURE latency (35 ms late): {est:?}");
    assert!((est.ms - 35.0).abs() < 1.5, "{est:?}");
    assert!(est.confidence > 0.8, "{est:?}");

    // a source that is not on the clock (another tempo) has no latency to speak of
    let other = (fpb * 1.07) as usize;
    g.click = Box::new(move |f| if f % other == 3 { 1.0 } else { 0.0 });
    g.run((fpb * 24.0) as usize);
    let lr = live::latency_ref(&g.e, 0, 12.0).unwrap();
    let on = djhost::analysis::dsp_onsets(&lr.window.audio, SR);
    let times: Vec<f64> = on.iter().map(|o| o.0).collect();
    let w: Vec<f64> = on.iter().map(|o| o.1).collect();
    let est = djengine::beatgrid::estimate_latency(&times, &w, lr.period, lr.origin).unwrap();
    assert!(est.confidence < 0.5, "{est:?}");
}

#[test]
fn without_a_clock_there_is_nothing_to_be_late_against() {
    let mut g = Rig::new(7);
    g.beats(6.0);
    let e = live::latency_ref(&g.e, 0, 12.0).unwrap_err();
    assert!(e.contains("master clock") || e.contains("2 s"), "{e}");
}
